"""Turn results/raw.jsonl into results/summary.md and LaTeX table rows results/tables.tex.
Run from the project root:  python -m experiments.summarize"""
import json
import os
from collections import defaultdict

import numpy as np

HERE = os.path.join(os.path.dirname(__file__), "..", "results")

# Values reported in the paper (Table 1, d, s0=100; Table 4, DNN-OSPG) for comparison.
PAPER = {
    ("maxcall_d=20", "DOS"): 50.86, ("maxcall_d=20", "FQI-MLP"): 50.92,
    ("maxcall_d=20", "FQI-GRU"): 50.76, ("maxcall_d=20", "OSPG-MLP"): 51.02,
    ("maxcall_d=20", "OSPG-GRU"): 50.99,
    ("maxcall_d=50", "DOS"): 68.87, ("maxcall_d=50", "FQI-MLP"): 68.91,
    ("maxcall_d=50", "FQI-GRU"): 68.98, ("maxcall_d=50", "OSPG-MLP"): 69.06,
    ("maxcall_d=50", "OSPG-GRU"): 68.93,
    ("geocall_d=7", "OSPG-MLP"): 10.2518, ("geocall_d=7", "LSM"): 10.1736,
    ("geocall_d=7", "FQI-MLP"): 10.1022,
    ("geocall_d=20", "OSPG-MLP"): 10.0100, ("geocall_d=20", "LSM"): 9.5964,
    ("geocall_d=20", "FQI-MLP"): 9.6372,
}
# Reference prices for the max-call: Becker, Cheridito and Jentzen (2019), Table 1, point
# estimates from their lower/upper bounds ([51.571, 51.765] and [69.582, 69.889]).
REFERENCE = {"maxcall_d=20": 51.668, "maxcall_d=50": 69.736}
ORDER = ["Hold", "LSM", "LSM-lags3", "DOS", "FQI-MLP", "FQI-GRU", "OSPG-MLP", "OSPG-GRU"]


def load():
    """All results in results/raw.jsonl and any per-experiment results/raw_*.jsonl files."""
    rows = []
    for name in sorted(os.listdir(HERE)):
        if name == "raw.jsonl" or (name.startswith("raw_") and name.endswith(".jsonl")):
            with open(os.path.join(HERE, name)) as f:
                rows += [json.loads(l) for l in f if l.strip()]
    return rows


def summarize(rows):
    groups = defaultdict(list)
    for r in rows:
        groups[(r["experiment"], r["problem"], r["method"])].append(r)
    out = []
    for (e, p, m), rs in groups.items():
        v = np.array([r["value"] for r in rs])
        out.append(dict(experiment=e, problem=p, method=m, n=len(rs), mean=v.mean(),
                        sd=v.std(ddof=1) if len(v) > 1 else np.nan,
                        stderr=np.mean([r["stderr"] for r in rs]),
                        mean_tau=np.mean([r["mean_tau"] for r in rs]),
                        seconds=np.mean([r["seconds"] for r in rs]),
                        reference=rs[0].get("reference") or REFERENCE.get(p),
                        paper=PAPER.get((p, m))))
    key = lambda s: (s["experiment"], s["problem"],
                     ORDER.index(s["method"]) if s["method"] in ORDER else 99)
    return sorted(out, key=key)


def fmt(x, nd=4):
    return "" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


def main():
    S = summarize(load())
    lines = ["# Results summary", "",
             "mean = average over seeds of the test-set value; sd = spread across seeds; "
             "se = Monte Carlo standard error of one test set; E5 values are mean returns "
             "per trade (fraction, after costs).", ""]
    cur = None
    for s in S:
        if (s["experiment"], s["problem"]) != cur:
            cur = (s["experiment"], s["problem"])
            lines += ["", f"## {cur[0]} - {cur[1]}", "",
                      "| method | seeds | mean | sd | se | reference | error % | paper | mean stop date | train s |",
                      "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
        err = 100 * (s["mean"] - s["reference"]) / s["reference"] if s["reference"] else None
        lines.append(f"| {s['method']} | {s['n']} | {fmt(s['mean'])} | {fmt(s['sd'])} | "
                     f"{fmt(s['stderr'])} | {fmt(s['reference'])} | {fmt(err, 2)} | "
                     f"{fmt(s['paper'])} | {s['mean_tau']:.1f} | {s['seconds']:.0f} |")
    with open(os.path.join(HERE, "summary.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    tex = ["% method & mean & sd & reference & paper   (generated by experiments/summarize.py)"]
    for s in S:
        tex.append(f"% {s['experiment']} {s['problem']}\n{s['method']} & {fmt(s['mean'], 3)} & "
                   f"{fmt(s['sd'], 3)} & {fmt(s['reference'], 3)} & {fmt(s['paper'], 3)} \\\\")
    with open(os.path.join(HERE, "tables.tex"), "w") as f:
        f.write("\n".join(tex) + "\n")
    with open(os.path.join(HERE, "replication_table.tex"), "w") as f:
        f.write(replication_table(S))
    print("\n".join(lines))


REPLICATION_COLUMNS = [("E1", "put_S0=36", "Put"), ("E2", "maxcall_d=20", "Max-call $d{=}20$"),
                       ("E2", "maxcall_d=50", "Max-call $d{=}50$"),
                       ("E3", "geocall_d=7", "Geo-call $d{=}7$"),
                       ("E3", "geocall_d=20", "Geo-call $d{=}20$")]


def replication_table(S):
    """Rows of the P1 replication table (E1-E3): one row per method with mean (sd over
    seeds) in each problem, then the reference values and the OSPG paper's values."""
    cell = {(s["problem"], s["method"]): s for s in S}
    methods = [m for m in ORDER if any((p, m) in cell for _, p, _ in REPLICATION_COLUMNS)]
    ref = {p: next((s["reference"] for s in S if s["problem"] == p and s["reference"]), None)
           for _, p, _ in REPLICATION_COLUMNS}
    nd = {"put_S0=36": 3, "geocall_d=7": 3, "geocall_d=20": 3}
    out = ["% generated by experiments/summarize.py: method & mean (sd) per problem",
           r"\begin{tabular}{l" + "r" * len(REPLICATION_COLUMNS) + "}", r"\toprule",
           "Method & " + " & ".join(c for _, _, c in REPLICATION_COLUMNS) + r" \\", r"\midrule"]
    for m in methods:
        vals = []
        for _, p, _ in REPLICATION_COLUMNS:
            s = cell.get((p, m))
            if s is None:
                vals.append("--")
                continue
            d = nd.get(p, 2)
            sd = "" if np.isnan(s["sd"]) else f" ({s['sd']:.{d}f})"
            vals.append(f"{s['mean']:.{d}f}{sd}")
        out.append(f"{m} & " + " & ".join(vals) + r" \\")
    out.append(r"\midrule")
    out.append("Reference & " + " & ".join(
        f"{ref[p]:.{nd.get(p, 2)}f}" if ref[p] else "--" for _, p, _ in REPLICATION_COLUMNS) + r" \\")
    paper = []
    for _, p, _ in REPLICATION_COLUMNS:
        v = PAPER.get((p, "OSPG-MLP"))
        paper.append(f"{v:.{nd.get(p, 2)}f}" if v else "--")
    out.append("Paper, DNN-OSPG & " + " & ".join(paper) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    main()
