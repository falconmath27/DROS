"""P2 ground truth: American put prices from the binomial tree and the finite-difference
(free-boundary PDE) solver, on the Longstaff-Schwartz grid S0 in {36,...,44},
sigma in {0.2, 0.4}, T in {1, 2}, K = 40, r = 0.06. Also the early-exercise boundary.
Run from the project root:  python -m experiments.benchmarks
Writes results/benchmarks.md, results/benchmarks_table.tex, results/boundary.csv
"""
import os
import time

import numpy as np

from baselines.binomial import binomial_price, black_scholes_put, exercise_boundary
from baselines.pde import fd_price, fd_solve

HERE = os.path.join(os.path.dirname(__file__), "..", "results")
K, r = 40.0, 0.06


def main():
    rows = []
    for S0 in (36, 38, 40, 42, 44):
        for sigma in (0.2, 0.4):
            for T in (1, 2):
                n_ex = 50 * T                                  # 50 exercise dates per year
                rows.append(dict(
                    S0=S0, sigma=sigma, T=T,
                    european=black_scholes_put(S0, K, r, sigma, T),
                    berm_tree=binomial_price(S0, K, r, sigma, T, 100 * n_ex, exercise_every=100),
                    berm_pde=fd_price(S0, K, r, sigma, T, exercise_every=1000 // 50, n_t=1000 * T),
                    amer_tree=binomial_price(S0, K, r, sigma, T, 5000 * T),
                    amer_pde=fd_price(S0, K, r, sigma, T, n_t=1000 * T)))
    head = ["S0", "sigma", "T", "European (BS)", "Bermudan tree", "Bermudan PDE",
            "American tree", "American PDE"]
    keys = ["european", "berm_tree", "berm_pde", "amer_tree", "amer_pde"]
    md = ["# American put benchmarks (K = 40, r = 0.06)", "",
          "Bermudan = 50 exercise dates per year. Tree: 5,000 steps per year-unit "
          "(Cox-Ross-Rubinstein). PDE: Crank-Nicolson, 1,000 log-price nodes, "
          "1,000 time steps per year, penalty iteration for early exercise.", "",
          "| " + " | ".join(head) + " |", "|" + " --- |" * len(head)]
    tex = ["% S0 & sigma & T & European & Bermudan tree & Bermudan PDE & American tree & "
           "American PDE   (generated by experiments/benchmarks.py)"]
    for w in rows:
        vals = [f"{w[k]:.3f}" for k in keys]
        md.append(f"| {w['S0']} | {w['sigma']} | {w['T']} | " + " | ".join(vals) + " |")
        tex.append(f"{w['S0']} & {w['sigma']} & {w['T']} & " + " & ".join(vals) + r" \\")
    gap = max(max(abs(w["berm_tree"] - w["berm_pde"]), abs(w["amer_tree"] - w["amer_pde"]))
              for w in rows)
    md += ["", f"Largest tree-PDE difference: {gap:.4f}."]

    out = fd_solve(36, K, r, 0.2, 1, n_t=1000)
    t_tree, b_tree = exercise_boundary(36, K, r, 0.2, 1, 1000)
    idx = np.arange(0, 1001, 50)
    csv = ["t,boundary_pde,boundary_tree"]
    for i in idx:
        bt = b_tree[i] if i < len(b_tree) else K
        csv.append(f"{out['t'][i]:.3f},{out['boundary'][i]:.4f},{bt:.4f}")
    md += ["", "## Early-exercise boundary, S0 = 36, sigma = 0.2, T = 1", "",
           "| t | PDE | tree |", "| --- | --- | --- |"]
    md += [f"| {c.split(',')[0]} | {c.split(',')[1]} | {c.split(',')[2]} |" for c in csv[1:]]

    with open(os.path.join(HERE, "benchmarks.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    with open(os.path.join(HERE, "benchmarks_table.tex"), "w") as f:
        f.write("\n".join(tex) + "\n")
    with open(os.path.join(HERE, "boundary.csv"), "w") as f:
        f.write("\n".join(csv) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    t0 = time.time()
    main()
    print(f"({time.time() - t0:.0f} s)")
