def pct(x):
    return f"{100 * x:+.2f}"


def p5_vs_hold():
    s = pd.read_csv(os.path.join(RES, "p5", "summary", "paired_statistics.csv"))
    s = s[(s.cost == 1) & (s.metric == "net_return") & (s.left == "OSPG-GRU")]
    out = ["% generated by experiments/report_tables.py from results/p5/summary/paired_statistics.csv",
           "% base cost (1x), economic net return per window in percent; OSPG-GRU minus comparator",
           r"\begin{tabular}{ll" + "c" * len(COMPARATORS) + "}", r"\toprule",
           "Market & Objective & " + " & ".join(LABEL[c] for c in COMPARATORS) + r" \\", r"\midrule"]
    for key, name in MARKETS:
        for obj in ("linear", "exponential"):
            cells = []
            for c in COMPARATORS:
                r = s[(s.market == key) & (s.objective == obj) & (s.right == c)]
                assert len(r) == 1, (key, obj, c)
                r = r.iloc[0]
                star = "$^{*}$" if r.p_value_holm < 0.05 else ""
                cells.append(f"{pct(r.estimate)}{star} [{pct(r.ci_lower)}, {pct(r.ci_upper)}]")
            out.append(f"{name} & {obj} & " + " & ".join(cells) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    write("p5_vs_hold.tex", out)


def p5_means():
    m = pd.read_csv(os.path.join(RES, "p5", "summary", "market_cost_tables.csv"))
    m = m[(m.cost == 1) & (m.metric == "net_return")]
    methods = ["Hold", "TakeProfitStopLoss", "TrailingStop", "LSM", "OSPG-MLP", "OSPG-GRU"]
    out = ["% generated by experiments/report_tables.py from results/p5/summary/market_cost_tables.csv",
           "% base cost (1x): mean economic net return per window, percent",
           r"\begin{tabular}{ll" + "r" * len(methods) + "r}", r"\toprule",
           "Market & Objective & " + " & ".join(LABEL[x] for x in methods) + r" & Windows \\", r"\midrule"]
    for key, name in MARKETS:
        for obj in ("linear", "exponential"):
            sub = m[(m.market == key) & (m.objective == obj)].set_index("method")
            cells = [f"{100 * sub.loc[x, 'mean']:.2f}" for x in methods]
            n = sub["n_windows"].unique()
            assert len(n) == 1, (key, obj, n)
            out.append(f"{name} & {obj} & " + " & ".join(cells) + f" & {int(n[0]):,}".replace(",", "{,}") + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    write("p5_means.tex", out)


def cell(r, star=True):
    s = "$^{*}$" if star and r.p_value_holm < 0.05 else ""
    return f"{pct(r.estimate)}{s} [{pct(r.ci_lower)}, {pct(r.ci_upper)}] & {r.p_value_holm:.3f}"


def p5_primary():
    """OSPG-GRU minus OSPG-MLP at base cost: net return and training-objective score."""
    s = pd.read_csv(os.path.join(RES, "p5", "summary", "paired_statistics.csv"))
    s = s[(s.cost == 1) & (s.left == "OSPG-GRU") & (s.right == "OSPG-MLP")]
    out = ["% generated by experiments/report_tables.py from results/p5/summary/paired_statistics.csv",
           "% base cost; OSPG-GRU minus OSPG-MLP, x100 (percentage points for net return)",
           r"\begin{tabular}{llcrcr}", r"\toprule",
           r"& & \multicolumn{2}{c}{Economic net return} & \multicolumn{2}{c}{Objective score} \\",
           r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}",
           r"Market & Objective & Difference [95\% CI] & Holm $p$ & Difference [95\% CI] & Holm $p$ \\",
           r"\midrule"]
    for key, name in MARKETS:
        for obj in ("linear", "exponential"):
            rows = {m: s[(s.market == key) & (s.objective == obj) & (s.metric == m)] for m in ("net_return", "objective")}
            assert all(len(v) == 1 for v in rows.values()), (key, obj)
            out.append(f"{name} & {obj} & {cell(rows['net_return'].iloc[0])} & "
                       f"{cell(rows['objective'].iloc[0])} \\\\")
    out += [r"\bottomrule", r"\end{tabular}"]
    write("p5_primary.tex", out)


def p5_slices(source, key_col, keys, labels, name):
    """OSPG-GRU and OSPG-MLP mean economic net return (percent) by cost level or calendar slice."""
    m = pd.read_csv(os.path.join(RES, "p5", "summary", source))
    m = m[(m.metric == "net_return") & m.method.isin(["OSPG-GRU", "OSPG-MLP"])]
    if key_col != "cost":
        m = m[m.cost == 1]
    head = " & ".join(rf"\multicolumn{{2}}{{c}}{{{lab}}}" for lab in labels)
    rules = "".join(rf"\cmidrule(lr){{{3 + 2 * i}-{4 + 2 * i}}}" for i in range(len(labels)))
    out = [f"% generated by experiments/report_tables.py from results/p5/summary/{source}",
           "% mean economic net return per window, percent; GRU and MLP columns",
           r"\begin{tabular}{ll" + "rr" * len(labels) + "}", r"\toprule",
           f"& & {head} \\\\", rules,
           "Market & Objective & " + " & ".join(["GRU & MLP"] * len(labels)) + r" \\", r"\midrule"]
    for mk, mname in MARKETS:
        for obj in ("linear", "exponential"):
            cells = []
            for k in keys:
                for meth in ("OSPG-GRU", "OSPG-MLP"):
                    r = m[(m.market == mk) & (m.objective == obj) & (m[key_col] == k) & (m.method == meth)]
                    cells.append("--" if r.empty else f"{100 * r['mean'].iloc[0]:.2f}")
            out.append(f"{mname} & {obj} & " + " & ".join(cells) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    write(name, out)


def persistence_corr():
    """Spearman rank correlation between training-period volatility persistence and the
    GRU-minus-MLP net return per asset and fold (results/p5/summary/persistence.csv), written
    as LaTeX macros \\perslinear and \\persexponential."""
    from scipy.stats import spearmanr
    p = pd.read_csv(os.path.join(RES, "p5", "summary", "persistence.csv")).dropna(
        subset=["persistence", "advantage"])
    out = ["% generated by experiments/report_tables.py from results/p5/summary/persistence.csv"]
    for obj in ("linear", "exponential"):
        g = p[p.objective == obj]
        rho = f"{spearmanr(g.persistence, g.advantage)[0]:+.2f}"
        rho = "0.00" if rho in ("+0.00", "-0.00") else rho
        out.append(rf"\newcommand{{\pers{obj}}}{{{rho}}}")
    write("persistence_corr.tex", out)


def main():
    persistence_corr()
    fbm_table()
    e4_table()
    fbm_compact()
    e4_compact()
    p5_vs_hold()
    p5_means()
    p5_primary()
    p5_slices("market_cost_tables.csv", "cost", [0, 1, 2],
              ["No costs", "Base costs", "Double costs"], "p5_costs.tex")
    p5_slices("regime_tables.csv", "regime", ["2020", "2022", "other years"],
              ["2020", "2022", "Other years"], "p5_regimes.tex")
    print("wrote", ", ".join(sorted(os.listdir(OUT))))


if __name__ == "__main__":
    main()
